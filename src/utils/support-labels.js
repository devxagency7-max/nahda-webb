/* --------------------------------------------------------------------------
   SUPPORT TYPE DISPLAY LABELS
   الاسم المعروض لنوع الدعم. الباك إند بيخزّن «لحمة» (اسم الإكسل القديم) وبيستقبله
   كفلتر زي ما هو، فالقيمة اللي بتتبعت للـ API ماتتغيرش — التسمية دي للعرض بس
   (الشاشات + ملفات الـ PDF): «لحمة» تتعرض «لحوم».
   -------------------------------------------------------------------------- */

const DISPLAY_LABELS = {
  'لحمة': 'لحوم',
  'لحمه': 'لحوم',
  'اللحمة': 'اللحوم',
  'اللحمه': 'اللحوم'
};

/** يرجّع الاسم المعروض لنوع دعم (أو النص زي ما هو لو مفيش بديل). */
export function supportTypeLabel(value) {
  if (value === undefined || value === null) return value;
  const text = String(value);
  return DISPLAY_LABELS[text.trim()] || text.replace(/لحمة|لحمه/g, 'لحوم');
}
